export function normalizeStopword(word) {
  if (!word) return ''
  let w = String(word).toLowerCase()
  w = w
    .replace(/[àáâäæãåā]/g, 'a')
    .replace(/[èéêëēėę]/g, 'e')
    .replace(/[ìíîïī]/g, 'i')
    .replace(/[òóôöøō]/g, 'o')
    .replace(/[ùúûüū]/g, 'u')
    .replace(/[ç]/g, 'c')
    .replace(/[ñ]/g, 'n')
  w = w.replace(/[''`’]/g, '')
  return w.trim()
}

