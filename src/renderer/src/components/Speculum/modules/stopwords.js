export const STOPWORD_MODES = [
  { value: 'none', label: 'Nessuna', languages: [] },
  { value: 'it', label: 'Italiano', languages: ['it'] },
  { value: 'en', label: 'Inglese', languages: ['en'] },
  { value: 'fr', label: 'Francese', languages: ['fr'] },
  { value: 'it+en', label: 'Italiano + Inglese', languages: ['it', 'en'] },
  { value: 'all', label: 'Italiano + Inglese + Francese', languages: ['it', 'en', 'fr'] },
  { value: 'custom', label: 'Personalizzata…', languages: [] }
]

export function getStopwordSet(mode = 'none', customRaw = '') {
  if (mode === 'none' || !mode) return new Set()

  if (mode === 'custom') {
    const tokens = String(customRaw || '')
      .split(/[\s,;]+/)
      .map((t) => normalizeStopword(t))
      .filter(Boolean)
    return new Set(tokens)
  }

  const def = STOPWORD_MODES.find((m) => m.value === mode)
  if (!def || def.languages.length === 0) return new Set()

  const result = new Set()
  for (const lang of def.languages) {
    const src = lang === 'it' ? STOPWORDS_IT : lang === 'en' ? STOPWORDS_EN : STOPWORDS_FR
    for (const w of src) result.add(w)
  }
  return result
}
